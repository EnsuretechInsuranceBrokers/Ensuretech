-- Legacy id spaces differ from this design's seeds (legacy relation 3 = daughter, here 3 = husband; the premium and sum-insured
-- numbering differs too). Anything migrated from, or exchanging ids with, the legacy system must go through this table.
-- Removed legacy ids (premium 11, 12, 14; sum-insured 10, 11, 12) are deliberately absent.
CREATE TABLE policy_svc.legacy_id_map (
    kind        TEXT     NOT NULL CHECK (kind IN ('RELATION', 'PREMIUM_TYPE', 'SUMINSURED_SUBTYPE')),
    legacy_id   SMALLINT NOT NULL,
    legacy_code TEXT     NOT NULL,
    legacy_name TEXT     NOT NULL,
    new_id      SMALLINT,
    status      TEXT     NOT NULL CHECK (status IN ('MAPPED', 'APPROXIMATE', 'UNMAPPED')),
    note        TEXT     NOT NULL DEFAULT '',
    PRIMARY KEY (kind, legacy_id),
    CHECK ((status = 'UNMAPPED') = (new_id IS NULL))
);

